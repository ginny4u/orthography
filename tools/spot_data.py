out = []
for it in ITEMS:
    bubbles = []; arts = set()
    for side, text in it:
        parts = []; pos = 0
        for m in TOK.finditer(text):
            if m.start() > pos: parts.append(text[pos:m.start()])
            x, o, a, w = m.group(1), m.group(2), int(m.group(3)), m.group(4)
            if a == 0: parts.append({'x': x})          # 함정: 눌러도 안 틀린 낱말(강조 없음)
            else: parts.append({'x': x, 'o': o, 'a': a, 'w': w}); arts.add(a)
            pos = m.end()
        if pos < len(text): parts.append(text[pos:])
        bubbles.append([side, parts])
    assert arts, it
    out.append({'t': bubbles, 'arts': sorted(arts)})

if __name__ == '__main__':
    js = '// tools/spot_data.py로 만든 파일. 직접 고치지 말 것.\nwindow.ORTH_SPOT = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
    open(sys.argv[1], 'w', encoding='utf-8').write(js)
    n = sum(1 for it in out for b in it['t'] for p in b[1] if isinstance(p, dict) and 'o' in p)
    print('items', len(out), 'errors', n)
