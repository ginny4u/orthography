def breakdown(word):
    if word in SPECIAL:
        return SPECIAL[word]
    parts = WORDS.get(word)
    if not parts:
        return None
    return [(p, PART.get(p)) for p in parts]

def table():
    out = {}
    for w in WORDS:
        b = breakdown(w)
        out[w] = [[p, h or ''] for p, h in b]
    return out

if __name__ == '__main__':
    for w, b in table().items():
        print(w, ' + '.join(p + ('(' + h + ')' if h else '') for p, h in b))
