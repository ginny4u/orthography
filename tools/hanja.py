# 해님의 ‘님’은 접미사
SPECIAL['해님'] = [('해', None), ('-님', '@접미사')]
SPECIAL['댓잎'] = [('대', None), ('잎', None)]
WORDS.setdefault('댓잎', ['대', '잎'])
SIX = ('곳간', '셋방', '숫자', '찻간', '툇간', '횟수')

def breakdown(word):
    if word in SPECIAL:
        return SPECIAL[word]
    parts = WORDS.get(word)
    if not parts:
        return None
    return [(p, PART.get(p)) for p in parts]

def table():
    # 요소: [글자, 한자 또는 '', 갈래('한'·'고'·'외'·'접')], 마지막에 [‘’, '', 이유] 한 줄(있으면)
    out = {}
    for w in WORDS:
        b = breakdown(w)
        row = []
        for p, h in b:
            if h and h.startswith('@'):
                row.append([p, '', {'@외래어': '외', '@접미사': '접'}[h]])
            else:
                row.append([p, h or '', '한' if h else '고'])
        note = NOTE.get(w)
        if not note and all(x[2] == '한' for x in row):
            note = ('두 음절 한자어 예외 여섯 단어(곳간·셋방·숫자·찻간·툇간·횟수) → 사이시옷을 적음' if w in SIX
                    else '한자어끼리 → 사이시옷 없음(예외 여섯 단어만)')
        if note:
            row.append(['', '', '', note])
        out[w] = row
    return out

